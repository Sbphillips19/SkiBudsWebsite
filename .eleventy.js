/* ==========================================================================
   Eleventy Configuration for SkiBuds Website
   NOTE: Eleventy 3.1 does not resolve eleventy.config.ts — this file is the
   live project config (.eleventy.js has top resolution priority).
   ========================================================================== */

const eleventyImage = require('@11ty/eleventy-img');
const htmlmin = require('html-minifier-terser');
const path = require('path');
const fs = require('fs');

module.exports = function (eleventyConfig) {
  // ---------------------------------------------------------------------------
  // Passthrough copies (assets that don't need processing)
  // ---------------------------------------------------------------------------
  eleventyConfig.addPassthroughCopy({ 'src/images': 'images' });
  eleventyConfig.addPassthroughCopy({ 'src/icons': 'icons' });
  eleventyConfig.addPassthroughCopy({ 'src/css': 'css' });
  eleventyConfig.addPassthroughCopy({ 'src/js': 'js' });
  eleventyConfig.addPassthroughCopy({ 'src/manifest.json': 'manifest.json' });
  eleventyConfig.addPassthroughCopy({ 'src/robots.txt': 'robots.txt' });
  eleventyConfig.addPassthroughCopy({ 'src/CNAME': 'CNAME' });
  eleventyConfig.addPassthroughCopy({ 'src/_headers': '_headers' });
  eleventyConfig.addPassthroughCopy({ 'src/_redirects': '_redirects' });
  // NOTE: sw.js is generated by Workbox (`npm run build:sw`), not passthrough-copied.

  // ---------------------------------------------------------------------------
  // Shortcodes
  // ---------------------------------------------------------------------------

  // Responsive image shortcode with WebP/AVIF + fallback
  async function imageShortcode(
    src,
    alt,
    sizes = '100vw',
    className = '',
    loading = 'lazy',
    fetchpriority = 'auto',
    widths = [320, 640, 960, 1280, 1920, 2560]
  ) {
    // Resolve image path relative to src directory
    let imagePath;
    if (src.startsWith('http')) {
      imagePath = src;
    } else if (src.startsWith('/')) {
      imagePath = `src${src}`;
    } else {
      imagePath = `src/images/${src}`;
    }

    const metadata = await eleventyImage.default(imagePath, {
      widths,
      formats: ['avif', 'webp', 'jpeg'],
      outputDir: './_site/images/optimized/',
      urlPath: '/images/optimized/',
      filenameFormat: function (id, src, width, format) {
        const ext = path.extname(src);
        const name = path.basename(src, ext);
        return `${name}-${width}w.${format}`;
      },
      sharpOptions: {
        animated: true,
      },
      avif: { quality: 50 },
      webp: { quality: 75 },
      jpeg: { quality: 80, mozjpeg: true },
    });

    const lowsrc = metadata.jpeg[0];

    // Generate source elements for each format
    const sourceAvif = metadata.avif
      .map(entry => `<source type="image/avif" srcset="${entry.url}" sizes="${sizes}">`)
      .join('');
    const sourceWebp = metadata.webp
      .map(entry => `<source type="image/webp" srcset="${entry.url}" sizes="${sizes}">`)
      .join('');
    const sourceJpeg = metadata.jpeg
      .map(entry => `<source type="image/jpeg" srcset="${entry.url}" sizes="${sizes}">`)
      .join('');

    const fetchpriorityAttr = fetchpriority !== 'auto' ? ` fetchpriority="${fetchpriority}"` : '';
    const imgAttrs = `class="${className}" loading="${loading}" alt="${alt}" decoding="async" width="${lowsrc.width}" height="${lowsrc.height}"${fetchpriorityAttr}`;

    return `<picture>${sourceAvif}${sourceWebp}${sourceJpeg}<img ${imgAttrs} src="${lowsrc.url}"></picture>`;
  }
  eleventyConfig.addNunjucksAsyncShortcode('image', imageShortcode);
  eleventyConfig.addLiquidShortcode('image', imageShortcode);
  eleventyConfig.addJavaScriptFunction('image', imageShortcode);

  // Inline SVG shortcode
  eleventyConfig.addShortcode('inlineSvg', function (name) {
    const svgPath = `src/_includes/svg/${name}.svg`;
    if (fs.existsSync(svgPath)) {
      return fs.readFileSync(svgPath, 'utf8');
    }
    return `<!-- SVG not found: ${name} -->`;
  });

  // Current year shortcode
  eleventyConfig.addShortcode('year', () => new Date().getFullYear());

  // Canonical URL shortcode
  eleventyConfig.addShortcode('canonical', function (page) {
    const base = 'https://skibudsapp.com';
    const url = page.url.replace('/index.html', '/');
    return `${base}${url}`;
  });

  // ---------------------------------------------------------------------------
  // Filters
  // ---------------------------------------------------------------------------
  eleventyConfig.addFilter('dateDisplay', date => {
    return new Date(date).toLocaleDateString('en-US', {
      year: 'numeric',
      month: 'long',
      day: 'numeric',
    });
  });

  eleventyConfig.addFilter('comma', num => {
    return Number(num).toLocaleString();
  });

  eleventyConfig.addFilter('json', value => JSON.stringify(value));

  // W3C date (YYYY-MM-DD) for sitemap <lastmod>
  eleventyConfig.addFilter('isoDate', date => {
    return new Date(date).toISOString().slice(0, 10);
  });

  // RFC-822 date for RSS lastBuildDate/pubDate
  eleventyConfig.addFilter('rfc822Date', date => {
    return new Date(date).toUTCString();
  });

  // ---------------------------------------------------------------------------
  // Transforms
  // ---------------------------------------------------------------------------
  eleventyConfig.addTransform('htmlmin', function (content, outputPath) {
    if (outputPath && outputPath.endsWith('.html')) {
      return htmlmin.minify(content, {
        useShortDoctype: true,
        removeComments: true,
        collapseWhitespace: true,
        conservativeCollapse: true,
        minifyCSS: true,
        minifyJS: true,
      });
    }
    return content;
  });

  // ---------------------------------------------------------------------------
  // Collections
  // ---------------------------------------------------------------------------
  eleventyConfig.addCollection('pages', function (collectionApi) {
    return collectionApi
      .getAll()
      .filter(item => item.inputPath.endsWith('.njk') || item.inputPath.endsWith('.md'));
  });

  eleventyConfig.addCollection('blog', function (collectionApi) {
    return collectionApi
      .getAll()
      .filter(item => item.inputPath.startsWith('./src/blog/') && item.inputPath.endsWith('.md'))
      .sort((a, b) => b.date - a.date);
  });

  // ---------------------------------------------------------------------------
  // Watch targets
  // ---------------------------------------------------------------------------
  eleventyConfig.addWatchTarget('./src/_includes/');
  eleventyConfig.addWatchTarget('./src/_data/');

  return {
    dir: {
      input: 'src',
      output: '_site',
      includes: '_includes',
      data: '_data',
      layouts: '_includes/layouts',
    },
    templateFormats: ['njk', 'md', 'html', '11ty.js'],
    htmlTemplateEngine: 'njk',
    markdownTemplateEngine: 'njk',
    passthroughFileCopy: true,
  };
};
